  prefijo   text not null,
  siguiente bigint not null default 1 check (siguiente > 0)
);
insert into public.consecutivos (tipo, prefijo, siguiente) values
  ('COT','COT-',1), ('REM','REM-',1), ('FAC','FV-',1),
  ('OC','OC-',1),   ('COM','CP-',1),  ('AJU','AJ-',1), ('TRA','TR-',1)
