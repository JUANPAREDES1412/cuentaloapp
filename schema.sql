create or replace function public.siguiente_consecutivo(p_tipo text) returns text
language plpgsql security definer set search_path = public as $$
declare v text;
begin
  update consecutivos set siguiente = siguiente + 1 where tipo = p_tipo
  returning prefijo || (siguiente - 1)::text into v;
  if v is null then raise exception 'No existe consecutivo para %', p_tipo; end if;
  return v;
end $$;

