-- 1. USUARIOS, PERFILES Y ROLES
-- ---------------------------------------------------------------------
create table if not exists public.perfiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  email      text,
  nombre     text,
  rol        text not null default 'trabajador' check (rol in ('admin','trabajador')),
  activo     boolean not null default false,
  creado_en  timestamptz not null default now()
);

create or replace function public.es_activo() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from perfiles where id = auth.uid() and activo);
$$;

create or replace function public.es_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from perfiles where id = auth.uid() and activo and rol = 'admin');
$$;

-- Permite a la pantalla de inicio saber si debe mostrar "crear administrador"
create or replace function public.hay_usuarios() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from perfiles);
$$;

-- El PRIMER usuario registrado queda como administrador activo.
-- Los demás quedan como trabajadores INACTIVOS hasta que un admin los active.
create or replace function public.tg_nuevo_usuario() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_primero boolean;
begin
  select not exists (select 1 from perfiles) into v_primero;
  insert into perfiles (id, email, nombre, rol, activo)
  values (new.id, new.email,
          coalesce(nullif(new.raw_user_meta_data->>'nombre',''), split_part(new.email,'@',1)),
          case when v_primero then 'admin' else 'trabajador' end,
          v_primero);
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.tg_nuevo_usuario();

-- Nunca dejar el sistema sin un administrador activo
create or replace function public.tg_proteger_admin() returns trigger
language plpgsql set search_path = public as $$
begin
  new.id := old.id;
  if old.rol = 'admin' and old.activo and (new.rol <> 'admin' or not new.activo) then
    if not exists (select 1 from perfiles where rol = 'admin' and activo and id <> old.id) then
      raise exception 'Debe existir al menos un administrador activo';
    end if;
  end if;
  return new;
end $$;

drop trigger if exists tr_proteger_admin on public.perfiles;
create trigger tr_proteger_admin before update on public.perfiles
for each row execute function public.tg_proteger_admin();

