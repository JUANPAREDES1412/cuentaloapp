create or replace function public.registrar_pago(p jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare d documentos%rowtype; v numeric := nullif(p->>'valor','')::numeric;
begin
  if not es_activo() then raise exception 'Usuario no autorizado'; end if;
  select * into d from documentos where id = nullif(p->>'factura_id','')::bigint and tipo = 'FAC' for update;
  if not found then raise exception 'Factura no encontrada'; end if;
  if d.estado = 'ANULADA' then raise exception 'La factura está anulada'; end if;
  if v is null or v <= 0 then raise exception 'Valor del abono inválido'; end if;
  if v > d.saldo then raise exception 'El abono (%) supera el saldo de la factura (%)', v, d.saldo; end if;
  insert into pagos (factura_id, fecha, valor, medio, referencia, usuario_id)
  values (d.id, coalesce(nullif(p->>'fecha','')::date, current_date), v,
          nullif(p->>'medio',''), nullif(p->>'referencia',''), auth.uid());
  update documentos set saldo = saldo - v,
         estado = case when saldo - v <= 0 then 'PAGADA' else estado end
  where id = d.id;
end $$;

create or replace function public.eliminar_pago(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare pg pagos%rowtype;
begin
  if not es_admin() then raise exception 'Solo un administrador puede eliminar abonos'; end if;
  select * into pg from pagos where id = p_id for update;
  if not found then raise exception 'Abono no encontrado'; end if;
  delete from pagos where id = p_id;
  update documentos set saldo = saldo + pg.valor, estado = 'EMITIDA'
  where id = pg.factura_id and estado <> 'ANULADA';
end $$;

create or replace function public.cambiar_estado(p_id bigint, p_estado text) returns void
language plpgsql security definer set search_path = public as $$
declare d documentos%rowtype;
begin
  if not es_activo() then raise exception 'Usuario no autorizado'; end if;
  select * into d from documentos where id = p_id for update;
  if not found then raise exception 'Documento no encontrado'; end if;
  if d.tipo = 'COT' and p_estado in ('ABIERTA','APROBADA','RECHAZADA')
     and d.estado in ('ABIERTA','APROBADA','RECHAZADA') then
    update documentos set estado = p_estado where id = p_id;
  elsif d.tipo = 'OC' and p_estado = 'CERRADA' and d.estado in ('PENDIENTE','PARCIAL') then
    update documentos set estado = 'CERRADA' where id = p_id;
  else
    raise exception 'Cambio de estado no permitido (% → %)', d.estado, p_estado;
  end if;
end $$;

