-- ---------------------------------------------------------------------
-- 5. MOTOR DE INVENTARIO: movimiento con costo promedio ponderado
--    Toda entrada/salida pasa por aquí y deja su línea en el kardex.
--    Entrada: nuevo promedio = (saldo*prom + cant*costo) / (saldo + cant)
--    Salida:  sale al costo promedio vigente (el promedio no cambia)
--    Salida con costo (reversión): retira valor a ese costo y recalcula
-- ---------------------------------------------------------------------
create or replace function public.fn_mov(
  p_prod bigint, p_bod bigint, p_tipo text,
  p_entrada numeric, p_salida numeric, p_costo numeric,
  p_doc_tipo text, p_doc_id bigint, p_doc_numero text, p_detalle text
) returns numeric
language plpgsql security definer set search_path = public as $$
declare v inventario%rowtype; v_c numeric; v_cant numeric; v_prom numeric;
begin
  insert into inventario (producto_id, bodega_id) values (p_prod, p_bod) on conflict do nothing;
  select * into v from inventario where producto_id = p_prod and bodega_id = p_bod for update;

  if coalesce(p_entrada,0) > 0 then
    v_c    := greatest(coalesce(p_costo, v.costo_promedio), 0);
    v_cant := v.cantidad + p_entrada;
    v_prom := case when v.cantidad <= 0 then v_c
                   else (v.cantidad * v.costo_promedio + p_entrada * v_c) / v_cant end;
  else
    if v.cantidad < p_salida then
      raise exception 'Stock insuficiente de "%" en %: disponible %, requerido %',
        (select nombre from productos where id = p_prod),
        (select nombre from bodegas where id = p_bod),
        round(v.cantidad, 3), round(p_salida, 3);
    end if;
    v_cant := v.cantidad - p_salida;
    if p_costo is null then
      v_c := v.costo_promedio; v_prom := v.costo_promedio;
    else
      v_c := p_costo;
      v_prom := case when v_cant > 0
                     then greatest((v.cantidad * v.costo_promedio - p_salida * p_costo) / v_cant, 0)
                     else v.costo_promedio end;
    end if;
  end if;

  v_prom := round(v_prom, 4);
  update inventario set cantidad = v_cant, costo_promedio = v_prom, actualizado_en = now()
  where producto_id = p_prod and bodega_id = p_bod;

  insert into kardex (producto_id, bodega_id, tipo, doc_tipo, doc_id, doc_numero, detalle,
                      entrada, salida, costo_unitario, valor,
                      saldo_cantidad, saldo_costo_promedio, saldo_valor, usuario_id)
  values (p_prod, p_bod, p_tipo, p_doc_tipo, p_doc_id, p_doc_numero, p_detalle,
          coalesce(p_entrada,0), coalesce(p_salida,0), round(v_c,4),
          round((coalesce(p_entrada,0) + coalesce(p_salida,0)) * v_c, 2),
          v_cant, v_prom, round(v_cant * v_prom, 2), auth.uid());
  return v_c;
end $$;

-- ---------------------------------------------------------------------
-- 6. CREAR DOCUMENTOS COMERCIALES (COT, REM, FAC, OC, COM)
-- ---------------------------------------------------------------------
create or replace function public.crear_documento(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_tipo       text   := upper(coalesce(p->>'tipo',''));
  v_cliente    bigint := nullif(p->>'cliente_id','')::bigint;
  v_proveedor  bigint := nullif(p->>'proveedor_id','')::bigint;
  v_bod        bigint := nullif(p->>'bodega_id','')::bigint;
  v_fecha      date   := coalesce(nullif(p->>'fecha','')::date, current_date);
  v_fp         text   := upper(coalesce(nullif(p->>'forma_pago',''),'CONTADO'));
  v_venc       date   := nullif(p->>'fecha_vencimiento','')::date;
  v_origen     documentos%rowtype;
  v_tiene_origen boolean := false;
  v_desde_rem  boolean := false;
  v_mueve      boolean;
  v_id bigint; v_num text; v_estado text; v_tercero text;
  v_it jsonb; v_prod productos%rowtype;
  v_cant numeric; v_precio numeric; v_desc numeric; v_ivap numeric;
  v_bruto numeric; v_sub numeric; v_ivav numeric; v_costo numeric;
  t_bruto numeric := 0; t_sub numeric := 0; t_iva numeric := 0; v_total numeric;
  v_cupo numeric; v_deuda numeric;
begin
  if not es_activo() then raise exception 'Usuario no autorizado'; end if;
  if v_tipo not in ('COT','REM','FAC','OC','COM') then raise exception 'Tipo de documento inválido'; end if;
  if p->'items' is null or jsonb_typeof(p->'items') <> 'array' or jsonb_array_length(p->'items') = 0 then
    raise exception 'El documento no tiene productos';
  end if;

  if v_tipo in ('COT','REM','FAC') then
    if v_cliente is null then raise exception 'Seleccione un cliente'; end if;
    select nombre into v_tercero from clientes where id = v_cliente;
    v_proveedor := null;
  else
    if v_proveedor is null then raise exception 'Seleccione un proveedor'; end if;
    select nombre into v_tercero from proveedores where id = v_proveedor;
    v_cliente := null;
  end if;
  if v_tercero is null then raise exception 'El cliente o proveedor no existe'; end if;

  -- Documento origen (cotización -> remisión/factura, remisión -> factura, orden -> compra)
  if nullif(p->>'origen_id','') is not null then
    select * into v_origen from documentos where id = (p->>'origen_id')::bigint for update;
    v_tiene_origen := found;
    if v_tiene_origen then
      if v_origen.estado = 'ANULADA' then raise exception 'El documento origen % está anulado', v_origen.numero; end if;
      if not ((v_origen.tipo = 'COT' and v_tipo in ('REM','FAC'))
           or (v_origen.tipo = 'REM' and v_tipo = 'FAC')
           or (v_origen.tipo = 'OC'  and v_tipo = 'COM')) then
        raise exception 'No se puede generar % a partir de %', v_tipo, v_origen.tipo;
      end if;
      if v_origen.tipo = 'COT' and v_origen.estado not in ('ABIERTA','APROBADA') then
        raise exception 'La cotización % no está disponible (estado %)', v_origen.numero, v_origen.estado; end if;
      if v_origen.tipo = 'REM' and v_origen.estado <> 'PENDIENTE' then
        raise exception 'La remisión % ya fue facturada', v_origen.numero; end if;
      if v_origen.tipo = 'OC' and v_origen.estado not in ('PENDIENTE','PARCIAL') then
        raise exception 'La orden % no tiene cantidades pendientes por recibir', v_origen.numero; end if;
      v_desde_rem := v_origen.tipo = 'REM';
      if v_desde_rem then v_bod := v_origen.bodega_id; v_cliente := v_origen.cliente_id; end if;
    end if;
  end if;

  -- Factura desde remisión NO vuelve a descargar inventario
  v_mueve := v_tipo in ('REM','COM') or (v_tipo = 'FAC' and not v_desde_rem);
  if v_mueve then
    if v_bod is null then raise exception 'Seleccione una bodega'; end if;
    if not exists (select 1 from bodegas where id = v_bod and activo) then raise exception 'Bodega inválida o inactiva'; end if;
  end if;

  if v_tipo = 'FAC' then
    if v_fp not in ('CONTADO','CREDITO') then v_fp := 'CONTADO'; end if;
    if v_fp = 'CREDITO' and v_venc is null then
      select v_fecha + coalesce(dias_credito,0) into v_venc from clientes where id = v_cliente;
    end if;
    if v_fp = 'CONTADO' then v_venc := v_fecha; end if;
  else
    v_fp := null;
  end if;

  v_num := siguiente_consecutivo(v_tipo);
  v_estado := case v_tipo when 'COT' then 'ABIERTA' when 'OC' then 'PENDIENTE'
                          when 'REM' then 'PENDIENTE' when 'FAC' then 'EMITIDA' else 'RECIBIDA' end;

  insert into documentos (tipo, numero, fecha, cliente_id, proveedor_id, bodega_id, estado,
                          forma_pago, medio_pago, fecha_vencimiento, referencia, observaciones,
                          origen_id, usuario_id)
  values (v_tipo, v_num, v_fecha, v_cliente, v_proveedor, v_bod, v_estado,
          v_fp, case when v_tipo = 'FAC' then nullif(p->>'medio_pago','') end, v_venc,
          nullif(p->>'referencia',''), nullif(p->>'observaciones',''),
          case when v_tiene_origen then v_origen.id end, auth.uid())
  returning id into v_id;

  for v_it in select value from jsonb_array_elements(p->'items') loop
    select * into v_prod from productos where id = nullif(v_it->>'producto_id','')::bigint;
    if not found then raise exception 'Hay un producto inválido en el documento'; end if;

    v_cant   := coalesce(nullif(v_it->>'cantidad','')::numeric, 0);
    if v_cant <= 0 then raise exception 'Cantidad inválida para %', v_prod.nombre; end if;
    v_precio := greatest(coalesce(nullif(v_it->>'precio','')::numeric, 0), 0);
    v_desc   := least(greatest(coalesce(nullif(v_it->>'descuento_pct','')::numeric, 0), 0), 100);
    v_ivap   := greatest(coalesce(nullif(v_it->>'iva_pct','')::numeric, v_prod.iva), 0);
    v_bruto  := round(v_cant * v_precio, 2);
    v_sub    := round(v_bruto * (1 - v_desc / 100), 2);
    v_ivav   := round(v_sub * v_ivap / 100, 2);
    t_bruto  := t_bruto + v_bruto; t_sub := t_sub + v_sub; t_iva := t_iva + v_ivav;

    v_costo := null;
    if v_mueve then
      if v_tipo = 'COM' then
        -- Costo de entrada = valor neto (con descuento, sin IVA) / cantidad
        v_costo := fn_mov(v_prod.id, v_bod, 'ENTRADA COMPRA', v_cant, 0, v_sub / v_cant,
                          v_tipo, v_id, v_num, v_tercero);
      else
        v_costo := fn_mov(v_prod.id, v_bod,
                          case when v_tipo = 'REM' then 'SALIDA REMISIÓN' else 'SALIDA VENTA' end,
                          0, v_cant, null, v_tipo, v_id, v_num, v_tercero);
      end if;
    elsif v_desde_rem then
      select costo_unitario into v_costo from documento_items
      where documento_id = v_origen.id and producto_id = v_prod.id order by id limit 1;
    end if;

    insert into documento_items (documento_id, producto_id, descripcion, cantidad, precio,
                                 descuento_pct, iva_pct, subtotal, iva_valor, total, costo_unitario)
    values (v_id, v_prod.id, v_prod.nombre, v_cant, v_precio, v_desc, v_ivap,
            v_sub, v_ivav, v_sub + v_ivav, v_costo);

    -- Recepción de orden de compra: suma lo recibido
    if v_tiene_origen and v_origen.tipo = 'OC' then
      update documento_items set cantidad_recibida = cantidad_recibida + v_cant
      where id = (select id from documento_items
                  where documento_id = v_origen.id and producto_id = v_prod.id
                  order by (cantidad_recibida >= cantidad), id limit 1);
    end if;
  end loop;

  v_total := t_sub + t_iva;
  update documentos set subtotal = t_bruto, descuento = t_bruto - t_sub, iva = t_iva, total = v_total,
         saldo = case when v_tipo = 'FAC' then v_total else 0 end
  where id = v_id;

  if v_tipo = 'FAC' then
    if v_fp = 'CREDITO' then
      select cupo_credito into v_cupo from clientes where id = v_cliente;
      if coalesce(v_cupo,0) > 0 then
        select coalesce(sum(saldo),0) into v_deuda from documentos
        where tipo = 'FAC' and cliente_id = v_cliente and estado <> 'ANULADA';
        if v_deuda > v_cupo then
          raise exception 'La factura supera el cupo de crédito del cliente. Cupo: %, cartera con esta factura: %', v_cupo, v_deuda;
        end if;
      end if;
    else
      if v_total > 0 then
        insert into pagos (factura_id, fecha, valor, medio, referencia, usuario_id)
        values (v_id, v_fecha, v_total, coalesce(nullif(p->>'medio_pago',''),'EFECTIVO'), 'Pago de contado', auth.uid());
      end if;
      update documentos set saldo = 0, estado = 'PAGADA' where id = v_id;
    end if;
  end if;

  if v_tiene_origen then
    if v_origen.tipo = 'COT' then
      update documentos set estado = 'CONVERTIDA' where id = v_origen.id;
    elsif v_origen.tipo = 'REM' then
      update documentos set estado = 'FACTURADA' where id = v_origen.id;
    elsif v_origen.tipo = 'OC' then
      update documentos set estado = case when exists (
          select 1 from documento_items where documento_id = v_origen.id and cantidad_recibida < cantidad)
        then 'PARCIAL' else 'RECIBIDA' end
      where id = v_origen.id;
    end if;
  end if;

  return jsonb_build_object('id', v_id, 'numero', v_num);
end $$;

-- ---------------------------------------------------------------------
-- 7. ANULAR DOCUMENTOS (solo admin). Reversa el inventario en el kardex.
-- ---------------------------------------------------------------------
create or replace function public.anular_documento(p_id bigint, p_motivo text default null) returns void
language plpgsql security definer set search_path = public as $$
declare d documentos%rowtype; o documentos%rowtype; k record; it record;
begin
  if not es_admin() then raise exception 'Solo un administrador puede anular documentos'; end if;
  select * into d from documentos where id = p_id for update;
  if not found then raise exception 'Documento no encontrado'; end if;
  if d.estado = 'ANULADA' then raise exception 'El documento ya está anulado'; end if;
  if d.tipo = 'REM' and d.estado = 'FACTURADA' then
    raise exception 'La remisión está facturada. Anule primero la factura.'; end if;
  if d.tipo in ('COT','OC') and exists (select 1 from documentos where origen_id = d.id and estado <> 'ANULADA') then
    raise exception 'Este documento tiene documentos generados activos. Anúlelos primero.'; end if;

  for k in select * from kardex where doc_id = d.id and doc_tipo = d.tipo order by id desc loop
    if k.salida > 0 then
      perform fn_mov(k.producto_id, k.bodega_id, 'ANULACIÓN ' || d.tipo, k.salida, 0, k.costo_unitario,
                     'ANU', d.id, d.numero, 'Anula ' || d.numero);
    elsif k.entrada > 0 then
      perform fn_mov(k.producto_id, k.bodega_id, 'ANULACIÓN ' || d.tipo, 0, k.entrada, k.costo_unitario,
                     'ANU', d.id, d.numero, 'Anula ' || d.numero);
    end if;
  end loop;

  if d.origen_id is not null then
    select * into o from documentos where id = d.origen_id for update;
    if o.tipo = 'REM' then
      update documentos set estado = 'PENDIENTE' where id = o.id;
    elsif o.tipo = 'COT' and not exists (select 1 from documentos where origen_id = o.id and id <> d.id and estado <> 'ANULADA') then
      update documentos set estado = 'ABIERTA' where id = o.id;
    elsif o.tipo = 'OC' then
      for it in select producto_id, cantidad from documento_items where documento_id = d.id loop
        update documento_items set cantidad_recibida = greatest(cantidad_recibida - it.cantidad, 0)
        where id = (select id from documento_items where documento_id = o.id
                    and producto_id = it.producto_id and cantidad_recibida > 0 order by id desc limit 1);
      end loop;
      update documentos set estado = case
          when not exists (select 1 from documento_items where documento_id = o.id and cantidad_recibida > 0) then 'PENDIENTE'
          when exists (select 1 from documento_items where documento_id = o.id and cantidad_recibida < cantidad) then 'PARCIAL'
          else 'RECIBIDA' end
      where id = o.id and estado <> 'CERRADA';
    end if;
  end if;

  if d.tipo = 'FAC' then delete from pagos where factura_id = d.id; end if;

  update documentos set estado = 'ANULADA', saldo = 0,
    observaciones = trim(coalesce(observaciones,'') || ' [ANULADA ' || to_char(now(),'YYYY-MM-DD') || ': '
                         || coalesce(nullif(p_motivo,''),'sin motivo') || ']')
  where id = d.id;
end $$;

-- ---------------------------------------------------------------------
-- 8. AJUSTES Y TRASLADOS DE INVENTARIO (solo admin)
--    Modos de ajuste: ENTRADA, SALIDA, CONTEO (cantidad física), COSTO
-- ---------------------------------------------------------------------
create or replace function public.ajuste_inventario(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_bod bigint := nullif(p->>'bodega_id','')::bigint;
  v_motivo text := nullif(trim(coalesce(p->>'observaciones','')),'');
  v_id bigint; v_num text; v_it jsonb; v_prod productos%rowtype; v_inv inventario%rowtype;
  v_modo text; v_q numeric; v_c numeric; v_delta numeric; v_cu numeric; v_total numeric := 0;
begin
  if not es_admin() then raise exception 'Solo un administrador puede ajustar el inventario'; end if;
  if v_bod is null or not exists (select 1 from bodegas where id = v_bod) then raise exception 'Seleccione una bodega válida'; end if;
  if v_motivo is null then raise exception 'Indique el motivo del ajuste'; end if;
  if p->'items' is null or jsonb_typeof(p->'items') <> 'array' or jsonb_array_length(p->'items') = 0 then
    raise exception 'El ajuste no tiene productos'; end if;

  v_num := siguiente_consecutivo('AJU');
  insert into documentos (tipo, numero, fecha, bodega_id, estado, observaciones, usuario_id)
  values ('AJU', v_num, coalesce(nullif(p->>'fecha','')::date, current_date), v_bod, 'APLICADO', v_motivo, auth.uid())
  returning id into v_id;

  for v_it in select value from jsonb_array_elements(p->'items') loop
    select * into v_prod from productos where id = nullif(v_it->>'producto_id','')::bigint;
    if not found then raise exception 'Producto inválido en el ajuste'; end if;
    v_modo := upper(coalesce(v_it->>'modo','ENTRADA'));
    v_q    := coalesce(nullif(v_it->>'cantidad','')::numeric, 0);
    v_c    := nullif(v_it->>'costo','')::numeric;

    insert into inventario (producto_id, bodega_id) values (v_prod.id, v_bod) on conflict do nothing;
    select * into v_inv from inventario where producto_id = v_prod.id and bodega_id = v_bod for update;

    if v_modo = 'COSTO' then
      if v_c is null or v_c < 0 then raise exception 'Costo inválido para %', v_prod.nombre; end if;
      update inventario set costo_promedio = round(v_c,4), actualizado_en = now()
      where producto_id = v_prod.id and bodega_id = v_bod;
      insert into kardex (producto_id, bodega_id, tipo, doc_tipo, doc_id, doc_numero, detalle,
                          entrada, salida, costo_unitario, valor, saldo_cantidad, saldo_costo_promedio, saldo_valor, usuario_id)
      values (v_prod.id, v_bod, 'AJUSTE COSTO', 'AJU', v_id, v_num,
              'Costo anterior ' || round(v_inv.costo_promedio,2) || '. ' || v_motivo,
              0, 0, round(v_c,4), 0, v_inv.cantidad, round(v_c,4), round(v_inv.cantidad * v_c, 2), auth.uid());
      v_delta := 0; v_cu := v_c;
    else
      if v_modo = 'CONTEO' then
        if v_q < 0 then raise exception 'La cantidad contada no puede ser negativa (%)', v_prod.nombre; end if;
        v_delta := v_q - v_inv.cantidad;
      elsif v_modo = 'ENTRADA' then
        if v_q <= 0 then raise exception 'Cantidad inválida para %', v_prod.nombre; end if;
        v_delta := v_q;
      elsif v_modo = 'SALIDA' then
        if v_q <= 0 then raise exception 'Cantidad inválida para %', v_prod.nombre; end if;
        v_delta := -v_q;
      else
        raise exception 'Tipo de ajuste inválido: %', v_modo;
      end if;

      if v_delta > 0 then
        v_cu := fn_mov(v_prod.id, v_bod, 'AJUSTE ENTRADA', v_delta, 0, v_c, 'AJU', v_id, v_num, v_motivo);
      elsif v_delta < 0 then
        v_cu := fn_mov(v_prod.id, v_bod, 'AJUSTE SALIDA', 0, -v_delta, null, 'AJU', v_id, v_num, v_motivo);
      else
        v_cu := v_inv.costo_promedio;
      end if;
    end if;

    insert into documento_items (documento_id, producto_id, descripcion, cantidad, precio, total)
    values (v_id, v_prod.id, v_modo, v_delta, coalesce(v_cu,0), round(abs(v_delta) * coalesce(v_cu,0), 2));
    v_total := v_total + round(abs(v_delta) * coalesce(v_cu,0), 2);
  end loop;

  update documentos set total = v_total where id = v_id;
  return jsonb_build_object('id', v_id, 'numero', v_num);
end $$;

create or replace function public.traslado_inventario(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_o bigint := nullif(p->>'bodega_id','')::bigint;
  v_d bigint := nullif(p->>'bodega_destino_id','')::bigint;
  v_obs text := nullif(trim(coalesce(p->>'observaciones','')),'');
  v_no text; v_nd text; v_id bigint; v_num text; v_it jsonb; v_prod productos%rowtype;
  v_q numeric; v_c numeric; v_total numeric := 0;
begin
  if not es_admin() then raise exception 'Solo un administrador puede trasladar inventario'; end if;
  if v_o is null or v_d is null or v_o = v_d then raise exception 'Seleccione una bodega de origen y una de destino diferentes'; end if;
  select nombre into v_no from bodegas where id = v_o;
  select nombre into v_nd from bodegas where id = v_d and activo;
  if v_no is null or v_nd is null then raise exception 'Bodega inválida o inactiva'; end if;
  if p->'items' is null or jsonb_typeof(p->'items') <> 'array' or jsonb_array_length(p->'items') = 0 then
    raise exception 'El traslado no tiene productos'; end if;

  v_num := siguiente_consecutivo('TRA');
  insert into documentos (tipo, numero, fecha, bodega_id, bodega_destino_id, estado, observaciones, usuario_id)
  values ('TRA', v_num, coalesce(nullif(p->>'fecha','')::date, current_date), v_o, v_d, 'APLICADO', v_obs, auth.uid())
  returning id into v_id;

  for v_it in select value from jsonb_array_elements(p->'items') loop
    select * into v_prod from productos where id = nullif(v_it->>'producto_id','')::bigint;
    if not found then raise exception 'Producto inválido en el traslado'; end if;
    v_q := coalesce(nullif(v_it->>'cantidad','')::numeric, 0);
    if v_q <= 0 then raise exception 'Cantidad inválida para %', v_prod.nombre; end if;
    v_c := fn_mov(v_prod.id, v_o, 'TRASLADO SALIDA', 0, v_q, null, 'TRA', v_id, v_num, 'Hacia ' || v_nd);
    perform fn_mov(v_prod.id, v_d, 'TRASLADO ENTRADA', v_q, 0, v_c, 'TRA', v_id, v_num, 'Desde ' || v_no);
    insert into documento_items (documento_id, producto_id, descripcion, cantidad, precio, total)
    values (v_id, v_prod.id, 'TRASLADO', v_q, v_c, round(v_q * v_c, 2));
    v_total := v_total + round(v_q * v_c, 2);
  end loop;

  update documentos set total = v_total where id = v_id;
  return jsonb_build_object('id', v_id, 'numero', v_num);
end $$;

