-- 10. SEGURIDAD (Row Level Security)
--     Lectura: usuarios activos. Configuración/productos/bodegas: solo admin.
--     Inventario, documentos, kardex y pagos: SOLO mediante las funciones.
-- ---------------------------------------------------------------------
alter table public.perfiles        enable row level security;
alter table public.empresa         enable row level security;
alter table public.consecutivos    enable row level security;
alter table public.bodegas         enable row level security;
alter table public.productos       enable row level security;
alter table public.clientes        enable row level security;
alter table public.proveedores     enable row level security;
alter table public.inventario      enable row level security;
alter table public.documentos      enable row level security;
alter table public.documento_items enable row level security;
alter table public.kardex          enable row level security;
alter table public.pagos           enable row level security;

drop policy if exists perfiles_sel on public.perfiles;
drop policy if exists perfiles_upd on public.perfiles;
create policy perfiles_sel on public.perfiles for select to authenticated using (public.es_activo() or id = auth.uid());
create policy perfiles_upd on public.perfiles for update to authenticated using (public.es_admin()) with check (public.es_admin());

do $$
declare t text;
begin
  foreach t in array array['empresa','consecutivos','bodegas','productos'] loop
    execute format('drop policy if exists %I on public.%I', t||'_sel', t);
    execute format('drop policy if exists %I on public.%I', t||'_ins', t);
    execute format('drop policy if exists %I on public.%I', t||'_upd', t);
    execute format('drop policy if exists %I on public.%I', t||'_del', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.es_activo())', t||'_sel', t);
    execute format('create policy %I on public.%I for insert to authenticated with check (public.es_admin())', t||'_ins', t);
    execute format('create policy %I on public.%I for update to authenticated using (public.es_admin()) with check (public.es_admin())', t||'_upd', t);
    execute format('create policy %I on public.%I for delete to authenticated using (public.es_admin())', t||'_del', t);
  end loop;

  foreach t in array array['clientes','proveedores'] loop
    execute format('drop policy if exists %I on public.%I', t||'_sel', t);
    execute format('drop policy if exists %I on public.%I', t||'_ins', t);
    execute format('drop policy if exists %I on public.%I', t||'_upd', t);
    execute format('drop policy if exists %I on public.%I', t||'_del', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.es_activo())', t||'_sel', t);
    execute format('create policy %I on public.%I for insert to authenticated with check (public.es_activo())', t||'_ins', t);
    execute format('create policy %I on public.%I for update to authenticated using (public.es_activo()) with check (public.es_activo())', t||'_upd', t);
    execute format('create policy %I on public.%I for delete to authenticated using (public.es_admin())', t||'_del', t);
  end loop;

  foreach t in array array['inventario','documentos','documento_items','kardex','pagos'] loop
    execute format('drop policy if exists %I on public.%I', t||'_sel', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.es_activo())', t||'_sel', t);
  end loop;
end $$;

